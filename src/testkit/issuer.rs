use std::error::Error;
use std::io::Write;
use std::process::{Command, Stdio};
use std::time::{SystemTime, UNIX_EPOCH};

use axum::http::header::CONTENT_TYPE;
use axum::routing::get;
use axum::Router;
use base64::engine::general_purpose::URL_SAFE_NO_PAD;
use base64::Engine;
use jsonwebtoken::{encode, Algorithm, EncodingKey, Header};
use reqwest::Client;
use serde_json::{json, Map, Value};
use tokio::net::TcpListener;

use crate::iam::GoogleKeySet;
use crate::mcp::caller::{CallerTokenVerifier, PLATFORM_TENANT_CLAIM};

/// What can go wrong standing an issuer up.
type IssuerError = Box<dyn Error + Send + Sync>;

/// The key id every token a [`TestIssuer`] mints names.
const KID: &str = "testkit-issuer-key";

/// An issuer of caller tokens for tests: a fresh RSA key, its public half
/// served as a JWK set on a loopback port, and a minter.
///
/// The key is generated by the `openssl` CLI, which every developer machine
/// and CI runner carries; no crate this one links can generate an RSA key.
///
/// ```rust,ignore
/// let issuer = TestIssuer::start("pierre-mcp-server").await?;
/// let verifier = Arc::new(issuer.verifier("https://svc.example.com/mcp"));
/// let token = issuer.mint(&issuer.claims("https://svc.example.com/mcp", "user-1")
///     .tenant("tenant-a").scopes(&["profile:read"]).build())?;
/// ```
#[derive(Debug)]
pub struct TestIssuer {
    issuer: String,
    private_pem: String,
    jwks_url: String,
}

impl TestIssuer {
    /// A fresh key for `issuer`, whose JWK set is served at
    /// [`Self::jwks_url`] until the runtime shuts down.
    ///
    /// # Errors
    ///
    /// When `openssl` cannot be run or answers with something other than a
    /// key, or the loopback listener cannot be bound.
    pub async fn start(issuer: impl Into<String>) -> Result<Self, IssuerError> {
        let (private_pem, modulus) = generate_key()?;
        let jwks = json!({
            "keys": [{
                "kty": "RSA",
                "alg": "RS256",
                "use": "sig",
                "kid": KID,
                "n": modulus,
                "e": "AQAB",
            }]
        })
        .to_string();
        let listener = TcpListener::bind("127.0.0.1:0").await?;
        let addr = listener.local_addr()?;
        let app = Router::new().route(
            "/.well-known/jwks.json",
            get(move || {
                let jwks = jwks.clone();
                async move { ([(CONTENT_TYPE, "application/json")], jwks) }
            }),
        );
        tokio::spawn(async move { axum::serve(listener, app).await });
        Ok(Self {
            issuer: issuer.into(),
            private_pem,
            jwks_url: format!("http://{addr}/.well-known/jwks.json"),
        })
    }

    /// The `iss` the tokens carry.
    #[must_use]
    pub fn issuer(&self) -> &str {
        &self.issuer
    }

    /// Where the issuer's JWK set is served.
    #[must_use]
    pub fn jwks_url(&self) -> &str {
        &self.jwks_url
    }

    /// A verifier of this issuer's tokens for `audience`.
    #[must_use]
    pub fn verifier(&self, audience: impl Into<String>) -> CallerTokenVerifier {
        CallerTokenVerifier::new(
            &self.issuer,
            audience,
            GoogleKeySet::new(&self.jwks_url, Client::new()),
        )
    }

    /// The claims of a token for `sub` addressed to `audience`, from this
    /// issuer, valid for an hour from now.
    #[must_use]
    pub fn claims(&self, audience: &str, sub: &str) -> TestClaims {
        let now = now_secs();
        let mut claims = Map::new();
        claims.insert("iss".to_owned(), Value::from(self.issuer.clone()));
        claims.insert("aud".to_owned(), Value::from(audience));
        claims.insert("sub".to_owned(), Value::from(sub));
        claims.insert("iat".to_owned(), Value::from(now));
        claims.insert("exp".to_owned(), Value::from(now + 3600));
        TestClaims { claims }
    }

    /// `claims` signed with this issuer's key.
    ///
    /// # Errors
    ///
    /// When the key cannot be read or the claims cannot be encoded.
    pub fn mint(&self, claims: &Value) -> Result<String, IssuerError> {
        let mut header = Header::new(Algorithm::RS256);
        header.kid = Some(KID.to_owned());
        let key = EncodingKey::from_rsa_pem(self.private_pem.as_bytes())?;
        Ok(encode(&header, claims, &key)?)
    }
}

/// The claims of a test token, built up from [`TestIssuer::claims`].
#[derive(Debug, Clone)]
pub struct TestClaims {
    claims: Map<String, Value>,
}

impl TestClaims {
    /// Carry `tenant` in [`PLATFORM_TENANT_CLAIM`].
    #[must_use]
    pub fn tenant(self, tenant: &str) -> Self {
        self.set(PLATFORM_TENANT_CLAIM, Value::from(tenant))
    }

    /// Carry `scopes` as the space-delimited `scope` claim.
    #[must_use]
    pub fn scopes(self, scopes: &[&str]) -> Self {
        self.set("scope", Value::from(scopes.join(" ")))
    }

    /// Set `claim` to `value`, replacing what it held.
    #[must_use]
    pub fn set(mut self, claim: &str, value: Value) -> Self {
        self.claims.insert(claim.to_owned(), value);
        self
    }

    /// Leave `claim` out.
    #[must_use]
    pub fn without(mut self, claim: &str) -> Self {
        self.claims.remove(claim);
        self
    }

    /// The claims as the JSON object a token carries.
    #[must_use]
    pub fn build(self) -> Value {
        Value::Object(self.claims)
    }
}

/// Seconds since the Unix epoch.
fn now_secs() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_secs())
}

/// A fresh 2048-bit RSA key: its PEM, and its modulus as base64url.
fn generate_key() -> Result<(String, String), IssuerError> {
    let generated = Command::new("openssl")
        .args([
            "genpkey",
            "-algorithm",
            "RSA",
            "-pkeyopt",
            "rsa_keygen_bits:2048",
        ])
        .output()?;
    if !generated.status.success() {
        return Err(format!(
            "openssl could not generate a key: {}",
            String::from_utf8_lossy(&generated.stderr)
        )
        .into());
    }
    let private_pem = String::from_utf8(generated.stdout)?;

    let mut reading = Command::new("openssl")
        .args(["rsa", "-noout", "-modulus"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()?;
    reading
        .stdin
        .take()
        .ok_or("openssl took no stdin")?
        .write_all(private_pem.as_bytes())?;
    let read = reading.wait_with_output()?;
    if !read.status.success() {
        return Err(format!(
            "openssl could not read the modulus: {}",
            String::from_utf8_lossy(&read.stderr)
        )
        .into());
    }
    let printed = String::from_utf8(read.stdout)?;
    let hex = printed
        .trim()
        .strip_prefix("Modulus=")
        .ok_or("openssl printed no Modulus=")?;
    let bytes = (0..hex.len())
        .step_by(2)
        .map(|i| {
            hex.get(i..i + 2)
                .and_then(|pair| u8::from_str_radix(pair, 16).ok())
                .ok_or("the modulus is not hex")
        })
        .collect::<Result<Vec<u8>, _>>()?;
    Ok((private_pem, URL_SAFE_NO_PAD.encode(bytes)))
}
